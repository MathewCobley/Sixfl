    "                  {recentPlayerForm.map((item, index) => (",
    "                    <span",
    "                      key={`${item.kickoffAt.toISOString()}-${index}`}",
    "                      title={formatFixtureDate(item.kickoffAt)}",
    '                      className={`inline-flex h-9 w-9 items-center justify-center rounded-full border text-xs font-black ${',
    '                        item.outcome === "W"',
