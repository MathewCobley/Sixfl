const fs = require("node:fs");
const path = require("node:path");

const pagePath = path.join(
  process.cwd(),
  "src/app/player/team/[teamid]/page.tsx",
);
let source = fs.readFileSync(pagePath, "utf8");

function replaceRequired(before, after, label) {
  if (source.includes(after)) return;
  if (!source.includes(before)) {
    throw new Error(`Expected ${label} source was not found in player team page.`);
  }
  source = source.replace(before, after);
}

replaceRequired(
  [
    "function normaliseEmail(value: string | null | undefined) {",
    "  const email = value?.trim().toLowerCase();",
    "  return email || null;",
    "}",
  ].join("\n"),
  [
    "function normaliseEmail(value: string | null | undefined) {",
    "  const email = value?.trim().toLowerCase();",
    "  return email || null;",
    "}",
    "",
    "type PlayerContribution = {",
    "  name: string;",
    "  goals: number;",
    "  assists: number;",
    "  teamMemberId?: string;",
    "};",
    "",
    "function normalisePlayerStatName(value: string | null | undefined) {",
    '  return (value ?? "").trim().replace(/\\s+/g, " ").toLowerCase();',
    "}",
    "",
    "function parsePlayerContributions(value: unknown): PlayerContribution[] {",
    "  if (!Array.isArray(value)) return [];",
    "",
    "  return value",
    "    .map((item) => {",
    '      if (!item || typeof item !== "object") return null;',
    "      const row = item as Record<string, unknown>;",
    '      const name = String(row.name ?? "").trim();',
    "      const goals = Number(row.goals ?? 0);",
    "      const assists = Number(row.assists ?? 0);",
    "",
    "      if (",
    "        !name ||",
    "        !Number.isInteger(goals) ||",
    "        goals < 0 ||",
    "        !Number.isInteger(assists) ||",
    "        assists < 0",
    "      ) {",
    "        return null;",
    "      }",
    "",
    "      const contribution: PlayerContribution = { name, goals, assists };",
    '      if (typeof row.teamMemberId === "string" && row.teamMemberId.trim()) {',
    "        contribution.teamMemberId = row.teamMemberId.trim();",
    "      }",
    "      return contribution;",
    "    })",
    "    .filter((item): item is PlayerContribution => item !== null);",
    "}",
  ].join("\n"),
  "player contribution helpers",
);

replaceRequired(
  [
    "  if (!team) notFound();",
    "",
    "  const now = new Date();",
  ].join("\n"),
  [
    "  if (!team) notFound();",
    "",
    "  const playerMatchDetails = membership",
    "    ? await prisma.matchResultTeamMeta.findMany({",
    "        where: { teamId: teamid },",
    "        select: {",
    "          scorers: true,",
    "          playerOfMatchName: true,",
    "        },",
    "      })",
    "    : [];",
    "  const completedSelections = membership",
    "    ? await prisma.fixtureSelection.findMany({",
    "        where: {",
    "          teamMemberId: membership.id,",
    '          selectionStatus: "SELECTED",',
    "          fixture: { status: FixtureStatus.COMPLETED },",
    "        },",
    "        select: {",
    "          fixture: {",
    "            select: {",
    "              kickoffAt: true,",
    "              homeTeamId: true,",
    "              result: {",
    "                select: { homeScore: true, awayScore: true },",
    "              },",
    "            },",
    "          },",
    "        },",
    "      })",
    "    : [];",
    "",
    "  const playerStatName = normalisePlayerStatName(",
    "    membership?.user.name ?? user.name,",
    "  );",
    "  let playerGoals = 0;",
    "  let playerAssists = 0;",
    "  let playerOfMatchAwards = 0;",
    "",
    "  for (const detail of playerMatchDetails) {",
    "    for (const contribution of parsePlayerContributions(detail.scorers)) {",
    "      const matchesPlayer =",
    "        contribution.teamMemberId === membership?.id ||",
    "        normalisePlayerStatName(contribution.name) === playerStatName;",
    "      if (!matchesPlayer) continue;",
    "      playerGoals += contribution.goals;",
    "      playerAssists += contribution.assists;",
    "    }",
    "",
    "    if (",
    "      playerStatName &&",
    "      normalisePlayerStatName(detail.playerOfMatchName) === playerStatName",
    "    ) {",
    "      playerOfMatchAwards += 1;",
    "    }",
    "  }",
    "",
    "  const completedAppearances = completedSelections.length;",
    "  const completedMatchRecord = completedSelections",
    "    .filter((selection) => Boolean(selection.fixture.result))",
    "    .map((selection) => {",
    "      const result = selection.fixture.result;",
    "      if (!result) return null;",
    "      const isHomeTeam = selection.fixture.homeTeamId === teamid;",
    "      const teamScore = isHomeTeam ? result.homeScore : result.awayScore;",
    "      const opponentScore = isHomeTeam ? result.awayScore : result.homeScore;",
    "      const outcome = teamScore > opponentScore ? \"W\" : teamScore < opponentScore ? \"L\" : \"D\";",
    "      return { outcome, kickoffAt: selection.fixture.kickoffAt };",
    "    })",
    "    .filter((item): item is { outcome: \"W\" | \"D\" | \"L\"; kickoffAt: Date } => Boolean(item));",
    "  const playerWins = completedMatchRecord.filter((item) => item.outcome === \"W\").length;",
    "  const playerDraws = completedMatchRecord.filter((item) => item.outcome === \"D\").length;",
    "  const playerLosses = completedMatchRecord.filter((item) => item.outcome === \"L\").length;",
    "  const recentPlayerForm = completedMatchRecord",
    "    .slice()",
    "    .sort((a, b) => b.kickoffAt.getTime() - a.kickoffAt.getTime())",
    "    .slice(0, 5);",
    "  const goalInvolvements = playerGoals + playerAssists;",
    "",
    "  const now = new Date();",
  ].join("\n"),
  "player performance data",
);

